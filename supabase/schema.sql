create extension if not exists "pgcrypto";

create table if not exists public.lecturas_sensor (
  id bigint generated by default as identity primary key,
  humedad integer not null check (humedad >= 0 and humedad <= 100),
  estado_riego boolean not null default false,
  alarma_activa boolean not null default false,
  estado_suelo text not null default 'ok' check (estado_suelo in ('ok', 'seco', 'exceso')),
  created_at timestamptz not null default now()
);

alter table public.lecturas_sensor
  add column if not exists estado_suelo text not null default 'ok'
  check (estado_suelo in ('ok', 'seco', 'exceso'));

create index if not exists lecturas_sensor_created_at_idx
  on public.lecturas_sensor (created_at desc);

create table if not exists public.configuracion_sistema (
  id integer primary key default 1 check (id = 1),
  modo_automatico boolean not null default true,
  riego_manual_activo boolean not null default false,
  umbral_humedad_minima integer not null default 30 check (umbral_humedad_minima >= 0 and umbral_humedad_minima <= 100),
  updated_at timestamptz not null default now()
);

insert into public.configuracion_sistema (id)
values (1)
on conflict (id) do nothing;

alter table public.lecturas_sensor enable row level security;
alter table public.configuracion_sistema enable row level security;

grant usage on schema public to anon, authenticated, service_role;
grant select, insert, update, delete on public.lecturas_sensor to anon, authenticated, service_role;
grant select, insert, update, delete on public.configuracion_sistema to anon, authenticated, service_role;
grant usage, select on all sequences in schema public to anon, authenticated, service_role;

drop policy if exists "lecturas_sensor_all" on public.lecturas_sensor;
create policy "lecturas_sensor_all"
  on public.lecturas_sensor
  for all
  to anon, authenticated, service_role
  using (true)
  with check (true);

drop policy if exists "configuracion_sistema_all" on public.configuracion_sistema;
create policy "configuracion_sistema_all"
  on public.configuracion_sistema
  for all
  to anon, authenticated, service_role
  using (true)
  with check (true);

create or replace function public.touch_updated_at()
returns trigger
language plpgsql
as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

drop trigger if exists configuracion_sistema_touch on public.configuracion_sistema;
create trigger configuracion_sistema_touch
  before update on public.configuracion_sistema
  for each row execute function public.touch_updated_at();

do $$
begin
  if not exists (
    select 1 from pg_publication_tables
    where pubname = 'supabase_realtime'
      and schemaname = 'public'
      and tablename = 'lecturas_sensor'
  ) then
    alter publication supabase_realtime add table public.lecturas_sensor;
  end if;

  if not exists (
    select 1 from pg_publication_tables
    where pubname = 'supabase_realtime'
      and schemaname = 'public'
      and tablename = 'configuracion_sistema'
  ) then
    alter publication supabase_realtime add table public.configuracion_sistema;
  end if;
end $$;
